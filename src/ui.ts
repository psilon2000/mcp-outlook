import { readFileSync } from "node:fs";
import { z } from "zod";

// These selectors describe a specific, manually verified OWA deployment. No selector is accepted as a tool argument.
const uiSchema = z.object({
  appReady: z.string().min(1),
  mail: z.object({
    safeToList: z.boolean(),
    safeToOpen: z.boolean(),
    route: z.string().startsWith("#path=/"),
    viewReady: z.string().min(1),
    folder: z.string().min(1),
    folderNameAttribute: z.string().min(1),
    activeFolderName: z.string().min(1),
    listState: z.string().min(1),
    listFolderAttribute: z.string().min(1),
    listQueryAttribute: z.string().min(1),
    listReadyAttribute: z.string().min(1),
    rows: z.string().min(1),
    subject: z.string().min(1),
    sender: z.string().min(1),
    time: z.string().min(1),
    idAttribute: z.string().min(1),
    unreadAttribute: z.string().min(1),
    messageBody: z.string().min(1),
    paneMessageId: z.string().min(1),
    paneIdAttribute: z.string().min(1),
    searchInput: z.string().min(1).optional(),
    searchSubmit: z.string().min(1).optional(),
    searchResultMarker: z.string().min(1).optional(),
    searchAppliedAttribute: z.string().min(1).optional(),
  }).optional(),
  calendar: z.object({
    timeZone: z.string().min(1),
    dateInput: z.string().min(1),
    dateApply: z.string().min(1),
    activeDate: z.string().min(1),
    eventListState: z.string().min(1),
    eventListDateAttribute: z.string().min(1),
    eventListOwnerAttribute: z.string().min(1),
    eventListReadyAttribute: z.string().min(1),
    calendarItems: z.string().min(1),
    calendarNameAttribute: z.string().min(1),
    selectedCalendar: z.string().min(1),
    eventItems: z.string().min(1),
    eventIdAttribute: z.string().min(1),
    eventOwnerAttribute: z.string().min(1),
    detailAccessAttribute: z.string().min(1),
    subject: z.string().min(1),
    when: z.string().min(1),
    details: z.string().min(1),
    detailsIdAttribute: z.string().min(1),
    addButton: z.string().min(1).optional(),
    addAddress: z.string().min(1).optional(),
    addSelectedAddress: z.string().min(1).optional(),
    addSave: z.string().min(1).optional(),
    addedCalendar: z.string().min(1).optional(),
  }).optional(),
  editor: z.object({
    newButton: z.string().min(1),
    subject: z.string().min(1),
    start: z.string().min(1),
    end: z.string().min(1),
    timeZone: z.string().min(1),
    timeZoneValues: z.record(z.string()).default({}),
    body: z.string().min(1),
    bodyMode: z.enum(["input", "contenteditable"]),
    location: z.string().min(1),
    allDay: z.string().min(1).optional(),
    attendeeInputs: z.record(z.string()).default({}),
    resolvedAttendees: z.record(z.string()).default({}),
    recurrenceFrequency: z.string().min(1),
    recurrenceInterval: z.string().min(1).optional(),
    recurrenceWeekdays: z.record(z.string()).default({}),
    recurrenceMonthDay: z.string().min(1).optional(),
    recurrenceOrdinal: z.string().min(1).optional(),
    recurrenceMonth: z.string().min(1).optional(),
    recurrenceMode: z.string().min(1).optional(),
    recurrenceModeValues: z.object({ monthDay: z.string().min(1), ordinal: z.string().min(1) }).optional(),
    recurrenceEndType: z.string().min(1).optional(),
    recurrenceEndValue: z.string().min(1).optional(),
    save: z.string().min(1),
    // Values from the verified UI, not guesses about the OWA API.
    frequencyValues: z.record(z.string()).default({}),
    endValues: z.record(z.string()).default({}),
    ordinalValues: z.record(z.string()).default({}),
    saveConfirmation: z.string().min(1),
    saveConfirmationAttribute: z.string().min(1),
    saveConfirmationValue: z.string().min(1),
  }).optional(),
});

export type UiMap = z.infer<typeof uiSchema>;

export function loadUiMap(path: string | undefined): UiMap | undefined {
  if (!path) return undefined;
  return uiSchema.parse(JSON.parse(readFileSync(path, "utf8")));
}
